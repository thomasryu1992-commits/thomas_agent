@pytest.mark.parametrize("name", ["kw_pipeline.py", "affiliate.py", "kw_taxonomy.py"])
def test_the_generated_port_opens_no_url_and_runs_nothing_at_import(name):
    source = (BLOG / name).read_text(encoding="utf-8")
    assert source.startswith("# GENERATED by scripts/blog_vendor.py")
    tree = ast.parse(source)
    imported = {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
    imported |= {n.module or "" for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)}
    assert not {"urllib.request", "urllib.error", "http.client", "socket", "subprocess", "selenium"} & imported
    assert "urlopen" not in source and "webdriver" not in source
    # Module level is definitions and plain constants only: no call reads a file or makes a directory on import.
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None:
            calls = [ast.unparse(c.func) for c in ast.walk(node.value) if isinstance(c, ast.Call)]
            assert not [c for c in calls if c in {"Cache", "_naver_day_max", "open", "io.open", "os.makedirs"}], ast.unparse(node)


def test_the_port_answers_the_network_only_from_the_recording():
    assert kp.VAULT == "" and kp.CACHE_DIR == "" and kp.REPLAY_DIR == ""
    kp_transport, kp._TRANSPORT = kp._TRANSPORT, None
    try:
        with pytest.raises(kp.ReplayMiss):
            kp.http("https://ac.search.naver.com/nx/ac?q=x")
    finally:
        kp._TRANSPORT = kp_transport
    transport = kr.Transport([{"url": "u1", "body": "a", "at": "2026-10-28T07:10:00+09:00", "epoch": 1.0},
                              {"url": "u1", "body": "b", "at": "2026-10-28T07:20:00+09:00", "epoch": 2.0},
                              {"url": "u2", "body": None}], kp.ReplayMiss)
    assert transport("u1") == "a" and transport.clock.minute == 10 and transport.epoch == 1.0
    assert [transport("u1"), transport("u1")] == ["b", "b"] and transport.clock.minute == 20
    with pytest.raises(kr.RecordedFailure):
        transport("u2")
    with pytest.raises(kp.ReplayMiss):
        transport("never-fetched")
    assert (transport.served, transport.misses) == (3, 1)


