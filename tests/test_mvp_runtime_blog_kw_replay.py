def _cand(kw, lane="AI 활용", score=10.0, decision="CREATE_NEW"):
    return {"kw": kw, "lane": lane, "score": score, "decision": {"decision": decision, "rule": "C1", "matched": None}}


def test_the_comparison_names_each_moved_candidate():
    recorded = {"candidates": [_cand("a b"), _cand("c", score=9.0), _cand("d")], "tistory": [{"kw": "t"}],
                "out_of_league": [], "ranks": [{"file": "x.md", "rank": 3}]}
    same = kr.compare(recorded, json.loads(json.dumps(recorded)))
    assert same["agree"] is True and same["differ"] == []
    moved = {"candidates": [_cand("ab"), _cand("c", score=9.5), _cand("e")], "tistory": [{"kw": "t"}, {"kw": "u"}],
             "out_of_league": [], "ranks": [{"file": "x.md", "rank": 4}]}
    result = kr.compare(recorded, moved)
    assert result["agree"] is False
    assert {(d["kw"], d["field"]) for d in result["differ"]} == {("c", "score"), ("d", "missing"), ("e", "extra")}
    assert result["comparison"]["tistory_equal"] is False and result["comparison"]["ranks_equal"] is False
    assert result["comparison"]["candidates_recorded"] == result["comparison"]["candidates_replayed"] == 3


def _bundle(root: Path, name: str, *, shas=None, finished=True) -> Path:
    bundle = root / name
    (bundle / "cache").mkdir(parents=True)
    (bundle / "outputs").mkdir()
    meta = {"schema": kr.BUNDLE_SCHEMA, "started": "2026-10-28T07:10:00+09:00", "started_epoch": 1.0, "args": [],
            "has_vol": False, "decision_mode": "enforce", "tools_sha256": shas or dict(kp.GENERATED_FROM_SHA256),
            "finished": finished, "history": "2026-10-28.json"}
    (bundle / "meta.json").write_text(json.dumps(meta), encoding="utf-8")
    with gzip.open(bundle / "http.jsonl.gz", "wt", encoding="utf-8") as handle:
        handle.write("")
    with tarfile.open(bundle / "inputs.tar.gz", "w:gz"):
        pass
    (bundle / "outputs" / "2026-10-28.json").write_text(json.dumps({"candidates": []}), encoding="utf-8")
    return bundle


def test_a_bundle_from_other_tool_files_is_stale_not_compared(tmp_path):
    stale = dict(kp.GENERATED_FROM_SHA256, **{"blog_taxonomy.py": "0" * 64})
    result = kr.replay(_bundle(tmp_path, "20261028-071000", shas=stale))
    assert (result["state"], result["stale"], result["comparison"]) == ("generator_stale", ["blog_taxonomy.py"], None)


def test_an_unfinished_or_foreign_folder_is_not_a_bundle(tmp_path):
    _bundle(tmp_path, "20261028-071000", finished=False)
    _bundle(tmp_path, "20261027-071000")
    (tmp_path / "notes").mkdir()
    assert [b.name for b in kr.bundles(tmp_path)] == ["20261027-071000"]


def test_a_tar_member_that_leaves_the_work_folder_is_refused(tmp_path):
    bundle = _bundle(tmp_path / "b", "20261028-071000")
    evil = tmp_path / "evil.txt"
    evil.write_text("x", encoding="utf-8")
    with tarfile.open(bundle / "inputs.tar.gz", "w:gz") as tar:
        tar.add(evil, arcname="../escaped.txt")
    work = tmp_path / "work"
    work.mkdir()
    with pytest.raises(tarfile.TarError):
        kr._extract(bundle, work)
    assert not (tmp_path / "escaped.txt").exists()


def test_the_daily_fire_records_each_bundle_once(tmp_path):
    ledger = LedgerStore(tmp_path / "state" / LEDGER_REL)
    assert kr.fire(ledger, now=NOW, root=tmp_path / "absent") == "blog_kw_replay_no_bundles"
    root = tmp_path / "bundles"
    stale = dict(kp.GENERATED_FROM_SHA256, **{"kw_pipeline.py": "0" * 64})
    _bundle(root, "20261027-071000", shas=stale)
    (root / "20261028-071000").mkdir()                     # no meta: not a bundle yet
    assert kr.fire(ledger, now=NOW, root=root) == "blog_kw_replayed=20261027-071000:generator_stale"
    assert kr.fire(ledger, now=NOW, root=root) == "blog_kw_replay_nothing_new"
    rows = [r["record"] for r in ledger.iter_records(kinds=[kr.RECORD_KIND]) if r["kind"] == kr.RECORD_KIND]
    assert len(rows) == 1 and rows[0]["state"] == "generator_stale" and rows[0]["agree"] is None


def test_the_kind_is_maintenance_and_fires_through_the_scheduler(tmp_path, monkeypatch):
    assert KIND_BLOG_KW_REPLAY in KINDS and KIND_BLOG_KW_REPLAY in MAINTENANCE_KINDS
    monkeypatch.setenv(kr.REPLAY_DIR_ENV, str(tmp_path / "bundles"))
    state = tmp_path / "state"
    store = ScheduleStore(state)
    store.path.parent.mkdir(parents=True, exist_ok=True)
    store.add(build_schedule(kind=KIND_BLOG_KW_REPLAY, request="", interval_seconds=86400, created_by="op",
                             now="2026-10-27T01:00:00Z"))
    ledger = LedgerStore(state / LEDGER_REL)
    run_due(store, now=NOW, control_store=ControlStore(state), ledger=ledger, repo_root=state)
    terminal = [e for e in ledger.read_scheduler_events() if e["action"] in ("fired", "failed")][-1]
    assert terminal["action"] == "fired" and terminal["status"] == "blog_kw_replay_no_bundles"
