"""The blog department's verification (BLOG_DEPARTMENT v0.2 P2): the system re-checks each draft the outsourced
drafting cron reported, with the vault's rules generated into ``runtime/mvp_runtime/blog/``, and records whether the
verdicts agree.

Under test: the generated checkers open no URL and write no file; a draft is compared only when its bytes are the
ones the cron checked; link liveness (X2) is left out of the comparison; a path from a report cannot leave the
vault's ``content/``; and the daily fire writes one closed-schema record per report, once, with no path in it."""

from __future__ import annotations

import ast
import hashlib
import json
from pathlib import Path

import pytest

from runtime.mvp_runtime import blog_department as bd
from runtime.mvp_runtime import management_report as mr
from runtime.mvp_runtime.blog import verify as bv
from runtime.mvp_runtime.control import ControlStore
from runtime.mvp_runtime.scheduler import (
    KIND_BLOG_VERIFY, KINDS, MAINTENANCE_KINDS, ScheduleStore, build_schedule, run_due,
)
from runtime.mvp_runtime.store import LEDGER_REL, LedgerStore

NOW = "2026-10-27T01:00:00Z"          # 10:00 KST on 10-27
BLOG = Path(bv.__file__).parent
GENERATED = ("preflight.py", "variety.py", "taxonomy.py")
DRAFT = '---\ntitle: "시험"\nplatform: naver\nstatus: draft\ncreated: 2026-10-27\n---\n# 시험\n\n본문.\n'


def _codes(fail=None, warn=None):
    return {"FAIL": dict(fail or {}), "WARN": dict(warn or {})}


@pytest.fixture
def vault(tmp_path):
    for p in ("content/naver", "content/tistory", "ops/blog-runs"):
        (tmp_path / p).mkdir(parents=True)
    return tmp_path


def _write(vault, name, text=DRAFT):
    path = vault / "content" / "naver" / name
    path.write_text(text, encoding="utf-8")
    return f"content/naver/{name}", hashlib.sha256(path.read_bytes()).hexdigest()


def _report(vault, day, drafts):
    report = {"schema": "blog_run_report.v1", "run_date": day, "steps": {"draft": 0}, "drafts": drafts}
    (vault / "ops" / "blog-runs" / f"{day}.json").write_text(json.dumps(report, ensure_ascii=False), encoding="utf-8")


@pytest.mark.parametrize("name", GENERATED)
def test_the_generated_checkers_open_no_url_and_write_no_file(name):
    source = (BLOG / name).read_text(encoding="utf-8")
    assert source.startswith("# GENERATED by scripts/blog_vendor.py")
    tree = ast.parse(source)
    imported = {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
    imported |= {n.module or "" for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)}
    assert not {"urllib.request", "urllib.error", "http.client", "socket", "subprocess"} & imported
    assert "urlopen" not in source
    for call in (n for n in ast.walk(tree) if isinstance(n, ast.Call)):
        if getattr(call.func, "attr", getattr(call.func, "id", "")) == "open":
            modes = [a.value for a in call.args[1:2] if isinstance(a, ast.Constant)]
            modes += [k.value.value for k in call.keywords if k.arg == "mode" and isinstance(k.value, ast.Constant)]
            assert all(set(str(m)) <= {"r", "b"} for m in modes), ast.unparse(call)


def test_the_generated_preflight_runs_offline_on_a_real_draft(vault):
    rel, _ = _write(vault, "1.md", '---\nplatform: naver\nstatus: draft\n---\n# 제목\n\n[링크 확인 필요] 본문\n')
    found = bv.check_draft(vault, vault / rel)
    assert found["preflight"]["FAIL"]["F1"] == 3          # title, keywords, tags missing
    assert found["preflight"]["FAIL"]["P1"] >= 1          # a placeholder left in
    assert "X2" not in found["preflight"]["FAIL"] and "X2" not in found["preflight"]["WARN"]
    assert set(found["variety"]) == {"FAIL", "WARN"}


@pytest.mark.parametrize("rel", ["../outside.md", "content/../x.md", "/etc/passwd", "content/naver/../../x.md",
                                 "ops/blog-runs/x.md", 3, None])
def test_a_path_from_a_report_cannot_leave_the_vaults_content(vault, rel):
    assert bv.resolve(vault, rel) is None
    assert bv.verify_draft(vault, {"path": rel})["state"] == "outside"


def test_only_unchanged_bytes_are_compared(vault, monkeypatch):
    rel, digest = _write(vault, "1.md")
    monkeypatch.setattr(bv, "check_draft", lambda root, path: {"preflight": _codes(), "variety": _codes()})
    ok = {"codes": _codes()}
    assert bv.verify_draft(vault, {"path": rel, "preflight": ok, "variety": ok})["state"] == "no_hash"
    assert bv.verify_draft(vault, {"path": rel, "sha256": "0" * 64, "preflight": ok, "variety": ok})["state"] == "changed"
    assert bv.verify_draft(vault, {"path": "content/naver/gone.md", "sha256": digest})["state"] == "missing"
    assert bv.verify_draft(vault, {"path": rel, "sha256": digest, "preflight": {"exit": None}, "variety": ok})["state"] == "no_codes"
    row = bv.verify_draft(vault, {"path": rel, "sha256": digest, "preflight": ok, "variety": ok})
    assert (row["state"], row["agree"], row["differ"]) == ("compared", True, [])


def test_link_liveness_is_left_out_and_any_other_difference_is_named(vault, monkeypatch):
    rel, digest = _write(vault, "1.md")
    system = {"preflight": _codes({"S4": 1}, {"K1": 1}), "variety": _codes()}
    monkeypatch.setattr(bv, "check_draft", lambda root, path: system)
    online = {"codes": _codes({"S4": 1, "X2": 2}, {"K1": 1, "X2": 1})}
    row = bv.verify_draft(vault, {"path": rel, "sha256": digest, "preflight": online, "variety": {"codes": _codes()}})
    assert row["agree"] is True
    drifted = {"codes": _codes({"S4": 1}, {"K1": 2})}
    row = bv.verify_draft(vault, {"path": rel, "sha256": digest, "preflight": drifted, "variety": {"codes": _codes({"V2": 1})}})
    assert (row["agree"], row["differ"]) == (False, ["K1", "V2"])


def test_a_checker_crash_on_one_draft_is_recorded_not_raised(vault, monkeypatch):
    rel, digest = _write(vault, "1.md")

    def boom(root, path):
        raise ValueError("vendored rule broke")

    monkeypatch.setattr(bv, "check_draft", boom)
    ok = {"codes": _codes()}
    assert bv.verify_draft(vault, {"path": rel, "sha256": digest, "preflight": ok, "variety": ok})["state"] == "error:ValueError"


def test_the_daily_fire_records_each_report_once_without_paths(vault, tmp_path, monkeypatch):
    rel, digest = _write(vault, "비밀제목.md")
    ok = {"codes": _codes()}
    monkeypatch.setattr(bv, "check_draft", lambda root, path: {"preflight": _codes(), "variety": _codes()})
    _report(vault, "2026-10-27", [{"path": rel, "platform": "naver", "sha256": digest, "preflight": ok, "variety": ok},
                                  {"path": "../x.md"}])
    _report(vault, "2026-10-20", [{"path": rel, "sha256": digest, "preflight": ok, "variety": ok}])   # past the lookback
    ledger = LedgerStore(tmp_path / "state" / LEDGER_REL)
    status = bv.fire(ledger, now=NOW, vault_root=vault)
    assert status == "blog_verified=2026-10-27 compared=1 agreed=1"
    rows = [r["record"] for r in ledger.iter_records(kinds=[bv.RECORD_KIND]) if r["kind"] == bv.RECORD_KIND]
    assert len(rows) == 1 and rows[0]["summary"] == {"drafts": 2, "compared": 1, "agreed": 1, "differed": 0, "not_compared": 1}
    assert "비밀제목" not in json.dumps(rows[0], ensure_ascii=False) and "content/" not in json.dumps(rows[0])
    assert bv.fire(ledger, now=NOW, vault_root=vault) == "blog_verify_nothing_new"


def test_the_kind_is_maintenance_and_fires_through_the_scheduler(vault, tmp_path, monkeypatch):
    assert KIND_BLOG_VERIFY in KINDS and KIND_BLOG_VERIFY in MAINTENANCE_KINDS
    monkeypatch.setenv(bd.BLOG_VAULT_ROOT_ENV, str(vault))
    _write(vault, "1.md")
    _report(vault, "2026-10-27", [])
    state = tmp_path / "state"
    store = ScheduleStore(state)
    store.path.parent.mkdir(parents=True, exist_ok=True)
    store.add(build_schedule(kind=KIND_BLOG_VERIFY, request="", interval_seconds=86400, created_by="op",
                             now="2026-10-26T01:00:00Z"))
    ledger = LedgerStore(state / LEDGER_REL)
    run_due(store, now=NOW, control_store=ControlStore(state), ledger=ledger, repo_root=state)
    terminal = [e for e in ledger.read_scheduler_events() if e["action"] in ("fired", "failed")][-1]
    assert terminal["action"] == "fired" and terminal["status"].startswith("blog_verified=2026-10-27")


def test_the_weekly_report_shows_the_weeks_comparison(vault, tmp_path, monkeypatch):
    rel, digest = _write(vault, "1.md")
    monkeypatch.setattr(bv, "check_draft", lambda root, path: {"preflight": _codes({"S4": 1}), "variety": _codes()})
    ok = {"codes": _codes()}
    _report(vault, "2026-10-21", [{"path": rel, "sha256": digest, "preflight": ok, "variety": ok},
                                  {"path": rel, "preflight": ok, "variety": ok}])
    ledger = LedgerStore(tmp_path / "state" / LEDGER_REL)
    bv.fire(ledger, now="2026-10-22T01:00:00Z", vault_root=vault)
    (vault / "content" / "tistory" / "t.md").write_text(DRAFT, encoding="utf-8")   # the observation needs both folders
    summary = bd.verification_summary(ledger, now="2026-10-26T00:00:00Z")
    assert summary == {"runs": 1, "drafts": 2, "compared": 1, "agreed": 0, "differed": 1, "not_compared": 1,
                       "codes": [("S4", 1)]}
    data = {**bd.observe(vault, now="2026-10-26T00:00:00Z"), "verification": summary}

    class Empty:
        def iter_records_with_archive(self, **_):
            return iter([])

        def iter_events_with_archive(self, *_a, **_k):
            return iter([])

    class NoApprovals:
        def pending(self):
            return []

    class NoSchedules:
        def list(self):
            return []

    text = mr.render(mr.collect(now="2026-10-26T00:00:00Z", ledger=Empty(), schedules=NoSchedules(),
                                approval_store=NoApprovals(), blog=lambda: data))
    assert "[검수 대조] 1일 · 비교 1편 중 일치 0 · 다름 1(S4 1) · 비교 못 함 1" in text
