"""The blog department's slot shadow (BLOG_DEPARTMENT v0.2 P7): each reported Naver draft's slot recomputed with the
vault's ``naver_slot`` rule, generated into ``runtime/mvp_runtime/blog/``, on the vault as it stood when the draft
was written.

Under test:
- the generated rule opens no URL, writes no file and keeps nothing that reads the unmounted Naver reservations;
- the moment is rebuilt by leaving out the drafts numbered above the one compared, so a run's three drafts each
  agree with the slot they were given in turn;
- a day chosen by hand differs, and what the rule decided from is on the record;
- a slot moved after the report is marked ``moved``;
- a path from a report cannot leave ``content/naver``;
- the daily fire writes one closed-schema record per report, once, with no path in it, and counts Tistory drafts
  without comparing them."""

from __future__ import annotations

import ast
import json
from pathlib import Path

import pytest

from runtime.mvp_runtime import blog_department as bd
from runtime.mvp_runtime.blog import naver_slot as ns
from runtime.mvp_runtime.blog import slot as bs
from runtime.mvp_runtime.control import ControlStore
from runtime.mvp_runtime.scheduler import (
    KIND_BLOG_SLOT, KINDS, MAINTENANCE_KINDS, ScheduleStore, build_schedule, run_due,
)
from runtime.mvp_runtime.store import LEDGER_REL, LedgerStore

NOW = "2026-11-03T01:00:00Z"          # 10:00 KST on 11-03
PORT = Path(ns.__file__)


@pytest.fixture
def vault(tmp_path):
    for p in ("content/naver", "content/tistory", "ops/blog-runs"):
        (tmp_path / p).mkdir(parents=True)
    return tmp_path


def _draft(vault, name, scheduled, status="draft"):
    path = vault / "content" / "naver" / name
    path.write_text(f"---\ntitle: \"시험\"\nstatus: {status}\nscheduled: {scheduled}\n---\n본문\n", encoding="utf-8")
    return f"content/naver/{name}"


def _report(vault, day, drafts):
    report = {"schema": "blog_run_report.v1", "run_date": day, "steps": {"draft": 0}, "drafts": drafts}
    (vault / "ops" / "blog-runs" / f"{day}.json").write_text(json.dumps(report, ensure_ascii=False), encoding="utf-8")


def _run(vault, start=170):
    """A day's three drafts written the way the cron writes them: each takes the rule's next slot in turn."""
    ns.configure(vault)
    rows = []
    for k in range(3):
        name = f"{start + k}편-키워드{k}.md"
        rel = _draft(vault, name, "")
        slot = ns.next_slot(str(vault), str(vault / rel))
        _draft(vault, name, slot)
        rows.append({"path": rel, "platform": "naver", "scheduled": slot})
    return rows


def test_the_generated_rule_opens_no_url_writes_no_file_and_reads_no_reservation():
    source = PORT.read_text(encoding="utf-8")
    assert source.startswith("# GENERATED by scripts/blog_vendor.py") and "v0.2 P7" in source.splitlines()[1]
    tree = ast.parse(source)
    imported = {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
    imported |= {n.module or "" for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)}
    assert not {"urllib.request", "urllib.error", "http.client", "socket", "subprocess"} & imported
    for call in (n for n in ast.walk(tree) if isinstance(n, ast.Call)):
        if getattr(call.func, "attr", getattr(call.func, "id", "")) == "open":
            modes = [a.value for a in call.args[1:2] if isinstance(a, ast.Constant)]
            assert all(set(str(m)) <= {"r", "b"} for m in modes), ast.unparse(call)
    functions = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}
    assert {"next_slot", "configure"} <= functions
    assert not {"reserved", "plan_fix", "apply_fix", "main"} & functions
    assert not [n for n in tree.body if isinstance(n, ast.If) and "__name__" in ast.unparse(n.test)]


def test_each_draft_of_a_run_agrees_with_the_slot_it_was_given_in_turn(vault):
    _draft(vault, "160편-이전.md", "2026-11-14 10:20")
    rows = _run(vault)
    found = [bs.compare_draft(vault, r) for r in rows]
    assert [f["state"] for f in found] == ["compared"] * 3 and all(f["agree"] for f in found)
    assert [f["episode"] for f in found] == [170, 171, 172]
    assert found[0]["tail"] == {"date": "2026-11-14", "windows": [0], "drafts": 1}
    assert [f["computed"][:10] for f in found] == ["2026-11-14", "2026-11-14", "2026-11-15"]
    assert not any(f["moved"] for f in found)


def test_a_day_chosen_by_hand_differs_and_the_record_says_what_the_rule_saw(vault):
    _draft(vault, "160편-이전.md", "2026-11-14 10:20")
    rel = _draft(vault, "170편-손.md", "2026-11-20 18:00")
    found = bs.compare_draft(vault, {"path": rel, "platform": "naver", "scheduled": "2026-11-20 18:00"})
    assert found["state"] == "compared" and found["agree"] is False
    assert found["computed"].startswith("2026-11-14 15:") and found["reported"] == "2026-11-20 18:00"
    assert found["tail"] == {"date": "2026-11-14", "windows": [0], "drafts": 1}


def test_a_slot_moved_after_the_report_is_marked_moved(vault):
    _draft(vault, "160편-이전.md", "2026-11-14 10:20")
    rows = _run(vault)
    _draft(vault, "171편-키워드1.md", "2026-11-30 10:00")
    found = bs.compare_draft(vault, rows[1])
    assert found["agree"] is True and found["moved"] is True and found["file_now"] == "2026-11-30 10:00"


@pytest.mark.parametrize("rel, state", [
    ("../x.md", "outside"), ("content/tistory/1-a.md", "outside"), ("content/naver/../../ops/x.md", "outside"),
    ("content/naver/이름없음.md", "no_episode"), ("content/naver/999편-없음.md", "missing"),
])
def test_a_path_from_a_report_cannot_leave_content_naver(vault, rel, state):
    found = bs.compare_draft(vault, {"path": rel, "platform": "naver", "scheduled": "2026-11-14 10:20"})
    assert found["state"] == state and found["agree"] is None and found["computed"] is None


def test_no_reported_slot_and_no_day_to_continue_from_are_named(vault):
    rel = _draft(vault, "170편-a.md", "2026-11-14 10:20")
    assert bs.compare_draft(vault, {"path": rel, "scheduled": "곧"})["state"] == "no_slot"
    found = bs.compare_draft(vault, {"path": rel, "scheduled": "2026-11-14 10:20"})
    assert found["state"] == "no_tail" and found["agree"] is None     # the rule refuses: no other draft has a day


def test_the_rule_is_restored_after_each_comparison(vault):
    real = ns.drafts
    _draft(vault, "160편-이전.md", "2026-11-14 10:20")
    bs.compare_draft(vault, _run(vault)[0])
    assert ns.drafts is real


def test_the_daily_fire_records_each_report_once_without_paths(vault, tmp_path):
    _draft(vault, "160편-이전.md", "2026-11-14 10:20")
    rows = _run(vault)
    _report(vault, "2026-11-03", rows + [{"path": "content/tistory/1-a.md", "platform": "tistory",
                                          "scheduled": "2026-11-05 13:30"}])
    _report(vault, "2026-10-25", rows)                                  # past the lookback
    (vault / "ops" / "blog-runs" / "2026-11-02.json").write_text("{", encoding="utf-8")   # unreadable: skipped
    ledger = LedgerStore(tmp_path / "state" / LEDGER_REL)
    assert bs.fire(ledger, now=NOW, vault_root=vault) == "blog_slotted=2026-11-03 compared=3 agreed=3"
    records = [r["record"] for r in ledger.iter_records(kinds=[bs.RECORD_KIND]) if r["kind"] == bs.RECORD_KIND]
    assert len(records) == 1 and records[0]["summary"] == {
        "naver": 3, "compared": 3, "agreed": 3, "differed": 0, "moved": 0, "not_compared": 0, "tistory_not_compared": 1}
    text = json.dumps(records[0], ensure_ascii=False)
    assert "키워드" not in text and "content/" not in text and ".md" not in text
    assert bs.fire(ledger, now=NOW, vault_root=vault) == "blog_slot_nothing_new"


def test_the_kind_is_maintenance_and_fires_through_the_scheduler(vault, tmp_path, monkeypatch):
    assert KIND_BLOG_SLOT in KINDS and KIND_BLOG_SLOT in MAINTENANCE_KINDS
    monkeypatch.setenv(bd.BLOG_VAULT_ROOT_ENV, str(vault))
    _report(vault, "2026-11-03", [])
    state = tmp_path / "state"
    store = ScheduleStore(state)
    store.path.parent.mkdir(parents=True, exist_ok=True)
    store.add(build_schedule(kind=KIND_BLOG_SLOT, request="", interval_seconds=86400, created_by="op",
                             now="2026-11-02T01:00:00Z"))
    ledger = LedgerStore(state / LEDGER_REL)
    run_due(store, now=NOW, control_store=ControlStore(state), ledger=ledger, repo_root=state)
    terminal = [e for e in ledger.read_scheduler_events() if e["action"] in ("fired", "failed")][-1]
    assert terminal["action"] == "fired" and terminal["status"] == "blog_slotted=2026-11-03 compared=0 agreed=0"
