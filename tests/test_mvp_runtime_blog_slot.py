STARTED = "2026-11-02T23:00:00Z"      # 08:00 KST on 11-03


def _post(vault, name, status, *, scheduled=None, published=None, origin="tistory-only", created="2026-11-01"):
    lines = ["---", 'title: "시험"', f"status: {status}", f"created: {created}"]
    lines += [f"origin: {origin}"] if origin else ["source: \"[[1편-원본]]\""]
    lines += [f"scheduled: {scheduled}"] if scheduled else []
    lines += [f"published: {published}"] if published else []
    path = vault / "content" / "tistory" / name
    path.write_text("\n".join(lines) + "\n---\n본문\n", encoding="utf-8")
    return f"content/tistory/{name}"


def _at(day, slot, name):
    return f"{day} {tq.jitter(slot, name)}"


def _check(vault, rel, reported, started=STARTED, siblings=()):
    return bs.check_tistory(vault, {"path": rel, "platform": "tistory", "scheduled": reported}, started,
                            bs.tistory_schedule(vault),
                            frozenset((vault / s).resolve() for s in siblings))


def test_the_generated_queue_keeps_only_its_rules():
    source = Path(tq.__file__).read_text(encoding="utf-8")
    assert source.startswith("# GENERATED by scripts/blog_vendor.py") and "v0.2 P7" in source.splitlines()[1]
    tree = ast.parse(source)
    assert all(isinstance(n, (ast.Import, ast.Assign, ast.FunctionDef)) for n in tree.body)
    names = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}
    names |= {n.targets[0].id for n in tree.body if isinstance(n, ast.Assign)}
    assert names == {"KST", "MARGIN_MIN", "SLOTS", "NEW_SINCE", "NEW_PER_DAY", "ONLY_PER_DAY",
                     "fm", "kind", "key", "jitter", "is_new",
                     "OLD_SLOTS", "NEW_SLOTS", "FAST_SLOT", "SLOT_CUTOVER", "FAST_PER_DAY", "is_fast", "slots_for"}
    imported = {a.name for n in tree.body if isinstance(n, ast.Import) for a in n.names}
    assert not {"subprocess", "shutil", "tempfile"} & imported
    assert "print(" not in source and '"w"' not in source


