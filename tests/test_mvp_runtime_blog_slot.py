def _draft(vault, name, scheduled, status="draft"):
    path = vault / "content" / "naver" / name
    path.write_text(f"---\ntitle: \"시험\"\nstatus: {status}\nscheduled: {scheduled}\n---\n본문\n", encoding="utf-8")
    return f"content/naver/{name}"


def _report(vault, day, drafts):
    report = {"schema": "blog_run_report.v1", "run_date": day, "steps": {"draft": 0}, "drafts": drafts}
    (vault / "ops" / "blog-runs" / f"{day}.json").write_text(json.dumps(report, ensure_ascii=False), encoding="utf-8")


def _run(vault, start=170):
    """A day's three drafts written the way the cron writes them: each takes the rule's next slot in turn."""
    ns.configure(vault)
    rows = []
    for k in range(3):
        name = f"{start + k}편-키워드{k}.md"
        rel = _draft(vault, name, "")
        slot = ns.next_slot(str(vault), str(vault / rel))
        _draft(vault, name, slot)
        rows.append({"path": rel, "platform": "naver", "scheduled": slot})
    return rows


def test_the_generated_rule_opens_no_url_writes_no_file_and_reads_no_reservation():
    source = PORT.read_text(encoding="utf-8")
    assert source.startswith("# GENERATED by scripts/blog_vendor.py") and "v0.2 P7" in source.splitlines()[1]
    tree = ast.parse(source)
    imported = {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
    imported |= {n.module or "" for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)}
    assert not {"urllib.request", "urllib.error", "http.client", "socket", "subprocess"} & imported
    for call in (n for n in ast.walk(tree) if isinstance(n, ast.Call)):
        if getattr(call.func, "attr", getattr(call.func, "id", "")) == "open":
            modes = [a.value for a in call.args[1:2] if isinstance(a, ast.Constant)]
            assert all(set(str(m)) <= {"r", "b"} for m in modes), ast.unparse(call)
    functions = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}
    assert {"next_slot", "configure"} <= functions
    assert not {"reserved", "plan_fix", "apply_fix", "main"} & functions
    assert not [n for n in tree.body if isinstance(n, ast.If) and "__name__" in ast.unparse(n.test)]


def test_each_draft_of_a_run_agrees_with_the_slot_it_was_given_in_turn(vault):
    _draft(vault, "160편-이전.md", "2026-11-14 10:20")
    rows = _run(vault)
    found = [bs.compare_draft(vault, r) for r in rows]
    assert [f["state"] for f in found] == ["compared"] * 3 and all(f["agree"] for f in found)
    assert [f["episode"] for f in found] == [170, 171, 172]
    assert found[0]["tail"] == {"date": "2026-11-14", "windows": [0], "drafts": 1}
    assert [f["computed"][:10] for f in found] == ["2026-11-14", "2026-11-14", "2026-11-15"]
    assert not any(f["moved"] for f in found)


